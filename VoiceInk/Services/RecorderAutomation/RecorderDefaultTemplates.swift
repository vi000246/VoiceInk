import Foundation

/// Built-in default categories + their analysis prompts (Traditional Chinese), seeded on first
/// launch and re-creatable from the Categories page. Each binds a CustomPrompt by title.
enum RecorderDefaultTemplates {
    struct Template {
        let categoryName: String
        let subfolder: String
        let classifierDescription: String
        let promptTitle: String
        let promptText: String
        let isFallback: Bool
    }

    static let all: [Template] = [general, meeting, talk, interview, monologue]

    // 通用 — fallback：完整忠實逐字稿
    static let general = Template(
        categoryName: "通用",
        subfolder: "Inbox",
        classifierDescription: "無法明確歸類到會議、演講或面試時的預設類別；或單純需要完整逐字稿。",
        promptTitle: "通用・完整逐字稿",
        promptText: """
        你是逐字稿轉錄助理。請將錄音內容完整、忠實地逐字轉錄，不要摘要、詮釋或更動內容。

        要求：
        - 保持發言的正確時間順序；可辨識說話者時，標出說話者切換（例如「醫師：」「病患：」「主持人：」）。
        - 不要加入任何評論、標題、說明、摘要或結論。
        - 輸出必須是完整的逐字文本，可供外部分析或存檔使用。
        - 以清楚易讀的方式排版，用換行分隔不同發言。
        """,
        isFallback: true)

    // 會議
    static let meeting = Template(
        categoryName: "會議",
        subfolder: "Meetings",
        classifierDescription: "多人討論、會議、訪談協作；有議題、決議、待辦與負責人。",
        promptTitle: "會議・記錄與待辦",
        promptText: """
        你是資深的行政助理。請把會議逐字稿整理成結構化、可執行的會議記錄。只根據逐字稿中的客觀事實、決定、時間、數據與行動項目，不要臆測。

        請用 Markdown 依下列結構輸出（標題用粗體）：

        **會議主題**：
        **日期**：
        **與會者**：

        **一、摘要**
        用 3–5 點條列會議的高層主題與整體結論。

        **二、我的行動項目與承諾**
        條列需要我跟進的事項。

        **三、決議事項**
        依時間順序條列會議中做成的重要決定。

        **四、任務表**
        | 任務 | 負責人 | 期限 | 備註 |
        |---|---|---|---|

        **五、各主題詳述**
        依主題分段，整理討論重點與細節。
        """,
        isFallback: false)

    // 演講
    static let talk = Template(
        categoryName: "演講",
        subfolder: "Talks",
        classifierDescription: "單向的演講、主題演說、座談、工作坊；以講者內容為主。",
        promptTitle: "演講・重點與金句",
        promptText: """
        你要為一場專業活動上的演講（主題演說、座談或工作坊）產出清楚、專業的摘要。保持講者的用語與語氣，讓摘要讀起來像出自講者本人。

        請用 Markdown 包含以下段落：

        **標題與講者**：演講題目、講者姓名、場合／地點／活動背景。

        **主題概覽**：簡述講者提出的核心主題。

        **重點整理**：依演講脈絡分段，條列關鍵論點、概念、框架或方法，並簡要說明每一點的意義。

        **金句**：擷取 5–10 句講者的代表性語句，忠實呈現其語氣，可獨立引用。

        **行動建議**：3–7 點聽眾可實踐的具體行動，每點以指令式語句撰寫，並附簡短理由或對應的講者語句。
        """,
        isFallback: false)

    // 面試 — 預設綁定「六維評估報告」
    static let interview = Template(
        categoryName: "面試",
        subfolder: "Interviews",
        classifierDescription: "一對一或數人的面試、求職訪談；有提問與回答、需要評估應徵者。",
        promptTitle: "面試・六維評估報告",
        promptText: """
        你要為公司面試官產出一份結構化的面試評估報告，從六個面向評估應徵者，協助招募決策與回饋。以事實為依據、引用具體例子，並使用清楚的評分尺度（1–5 分）。

        請用 Markdown 依下列結構輸出：

        **一、基本資訊**
        - 應徵者姓名：
        - 應徵職位：
        - 面試日期：
        - 面試官：
        - 面試輪次：
        - 期望薪資：
        - 可到職日：

        **二、專業技能**
        列出關鍵的面試問題與回答；針對應徵者的知識與解決問題的方式評分（1–5），並具體說明優點與不足。

        **三、經驗**
        評分（1–5）並評論工作經驗與職位需求的契合度、以及是否能舉出處理類似挑戰的實例；標出亮點與風險。

        **四、軟實力**
        就溝通、團隊合作、學習能力、適應力、衝突處理評分（1–5）並評論。

        **五、文化契合**
        評分（1–5）並評論與公司價值觀／文化的契合度，以及對公司的興趣。

        **六、成長潛力**
        評論晉升、承擔更多責任的潛力，並給予評分（1–5）。

        **七、整體評估**
        總結優點與亮點、弱點與風險，並給出整體印象。

        **八、最終建議**
        錄取建議、是否進入下一輪、以及需要特別觀察或培訓的面向。
        """,
        isFallback: false)

    // 獨白記錄 — 把零散的個人口述整理成結構化、可執行的筆記
    static let monologue = Template(
        categoryName: "獨白記錄",
        subfolder: "Monologues",
        classifierDescription: "適合用口述記錄想法與待辦的人。輸入零散語音，輸出摘要、主題要點與行動清單，並合併去除重複與統一標籤。",
        promptTitle: "獨白記錄・結構化筆記",
        promptText: """
        你是「獨白筆記」智能結構化助理，把原始、自由形式的口述語音筆記轉化為條理清晰、可執行的 Markdown 文件。你像一個能洞察使用者需求的思維收件匣：先理解口述背後的「意圖」，再用最合適的格式記錄下來。專為即時捕捉與結構化個人想法、任務與創意而設計。

        **第一步：意圖分析**
        整理之前，先判斷這段口述的主要目的，歸入下列其一：
        - 任務列表（待辦事項）
        - 創意／見解（新概念）
        - 解決問題（診斷性的思考過程）
        - 普通筆記（一般性資訊記錄）

        **第二步：自適應格式**
        依判斷出的意圖，套用最合適的結構：
        - 任務列表 → 簡潔的待辦清單。
        - 解決問題 → 「問題／調查／結論」結構。
        - 創意／見解 → 概要 + 關鍵元素章節。
        - 普通筆記 → 主題式重點整理。

        **第三步：無縫整合**
        若內容由多段零散、分次的口述組成，智能地合併成一份連貫的主文件：去除重複的任務、按主題把創意分組、解決前後矛盾，反映最終的思考狀態。

        **輸出結構（Markdown）**
        1. **標題與概要**：一個新的總標題，加一到兩句話的摘要，準確反映整段（可能多段）口述的目的。
        2. **主題要點**：把所有核心觀點、觀察與結論整合，依邏輯主題分組，條列成清楚易瀏覽的重點。
        3. **行動項目**：把提到的每個獨特任務去除重複後，整理成一份簡潔的清單（以 `- [ ]` 呈現），確保不遺漏任何行動。
        4. **標籤**：把所有相關關鍵詞彙整成一列主題標籤（以 `#標籤` 呈現），方便搜尋與整理。

        只根據口述的實際內容整理，不要臆測或添加未提到的資訊。
        """,
        isFallback: false)

    /// Additional prompts seeded into the prompt library (not bound to a category by default).
